#!/usr/bin/env bash
# BearSSL as an Arduino source library for the ESP32 builds of ecdsa_bench / rsa_bench. arduino-pico bundles BearSSL in
# its core; arduino-esp32 has none. This packages the SAME code: earlephilhower/bearssl-esp8266 at the commit
# arduino-pico 6.1.1 pins (tools/libbearssl/bearssl), so the ESP32 rows compare like for like with the Pico's.
#   -> $IOT_PQC_CACHE/arduino-libs-esp32/bearssl   (run_benchmarks.py passes that dir for --board esp32)
# Layout: src/bearssl/*.h (the sketches include <bearssl/bearssl.h>), BearSSL's sources and inner.h under src/, and a
# src/bearssl.h shim for inner.h's #include "bearssl.h". arduino-cli compiles the sources with the sketch.
set -euo pipefail
CACHE=${IOT_PQC_CACHE:-$HOME/.cache/iot-pqc}
COMMIT=${BEARSSL_COMMIT:-aca13833b6f9ddffaea2041a01facc76829dc03b}   # arduino-pico 6.1.1's submodule
SRC="$CACHE/bearssl-esp8266-src" LIB="$CACHE/arduino-libs-esp32/bearssl"
STAMP="$LIB/.iot-pqc-build"
if [ "$(cat "$STAMP" 2>/dev/null)" = "$COMMIT" ]; then
    echo "[+] BearSSL Arduino library up to date -> $LIB"; exit 0
fi
[ -d "$SRC/.git" ] || git clone -q https://github.com/earlephilhower/bearssl-esp8266.git "$SRC"
git -C "$SRC" fetch -q origin "$COMMIT" 2>/dev/null || true
git -C "$SRC" checkout -q "$COMMIT"
rm -rf "$LIB" && mkdir -p "$LIB/src/bearssl"
cp "$SRC"/inc/*.h "$LIB/src/bearssl/"
(cd "$SRC/src" && find . -name '*.c' -o -name '*.h' | while read -r f; do
    mkdir -p "$LIB/src/$(dirname "$f")" && cp "$f" "$LIB/src/$f"; done)
printf '#include "bearssl/bearssl.h"\n' > "$LIB/src/bearssl.h"
cat > "$LIB/library.properties" <<EOF
name=bearssl
version=0.6.0+${COMMIT:0:7}
author=Thomas Pornin; ESP8266 / Pico fork by Earle F. Philhower III
maintainer=IoT-PQC (generated by pico/sketches/ecdsa_bench/make_bearssl_lib.sh)
sentence=BearSSL (bearssl-esp8266 at arduino-pico 6.1.1's commit) for the ESP32 builds
paragraph=
category=Other
url=https://github.com/earlephilhower/bearssl-esp8266
architectures=esp32
EOF
echo "$COMMIT" > "$STAMP"
echo "[+] BearSSL ${COMMIT:0:7} -> $LIB"
